\set ON_ERROR_STOP 0
\echo '=== S1: transition tables + column list (UPDATE OF status) ==='
CREATE SCHEMA ops;
CREATE TABLE ops.operations (
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  op_date timestamptz NOT NULL,
  amount numeric(14,2) NOT NULL,
  status smallint NOT NULL DEFAULT 0,
  operation_guid uuid NOT NULL DEFAULT gen_random_uuid(),
  client_id int NOT NULL,
  PRIMARY KEY (id, op_date),
  UNIQUE (operation_guid, op_date)
) PARTITION BY RANGE (op_date);
CREATE TABLE ops.operations_2026_10 PARTITION OF ops.operations FOR VALUES FROM ('2026-10-01') TO ('2026-11-01');
CREATE TABLE ops.operations_2026_11 PARTITION OF ops.operations FOR VALUES FROM ('2026-11-01') TO ('2026-12-01');
CREATE TABLE ops.operations_default PARTITION OF ops.operations DEFAULT;

CREATE FUNCTION ops.noop() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RETURN NULL; END $$;
CREATE TRIGGER t_col AFTER UPDATE OF status ON ops.operations
  REFERENCING OLD TABLE AS o NEW TABLE AS n FOR EACH STATEMENT EXECUTE FUNCTION ops.noop();

\echo '=== S2: composite FK to registry => declarative global uniqueness ==='
CREATE TABLE ops.operation_guid_registry (
  operation_guid uuid PRIMARY KEY,
  op_date timestamptz NOT NULL,
  UNIQUE (operation_guid, op_date)
);
CREATE FUNCTION ops.register_guid() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  INSERT INTO ops.operation_guid_registry VALUES (NEW.operation_guid, NEW.op_date);
  RETURN NEW;
END $$;
CREATE TRIGGER t_reg BEFORE INSERT ON ops.operations FOR EACH ROW EXECUTE FUNCTION ops.register_guid();
ALTER TABLE ops.operations ADD FOREIGN KEY (operation_guid, op_date)
  REFERENCES ops.operation_guid_registry (operation_guid, op_date);
INSERT INTO ops.operations (op_date, amount, operation_guid, client_id)
  VALUES ('2026-10-05', 10, '11111111-1111-1111-1111-111111111111', 1);
\echo '-- expect failure: same guid, other partition (trigger path)'
INSERT INTO ops.operations (op_date, amount, operation_guid, client_id)
  VALUES ('2026-11-05', 10, '11111111-1111-1111-1111-111111111111', 1);
\echo '-- expect failure: same guid, trigger DISABLED (pure constraint path)'
ALTER TABLE ops.operations DISABLE TRIGGER t_reg;
INSERT INTO ops.operations (op_date, amount, operation_guid, client_id)
  VALUES ('2026-11-05', 10, '11111111-1111-1111-1111-111111111111', 1);
ALTER TABLE ops.operations ENABLE TRIGGER t_reg;

\echo '=== S3: statement trigger with transition tables on partitioned root + REFRESH CONCURRENTLY inside ==='
INSERT INTO ops.operations (op_date, amount, client_id)
  SELECT '2026-10-01'::timestamptz + (g || ' hours')::interval, g, g % 5 FROM generate_series(1, 1000) g;
CREATE MATERIALIZED VIEW ops.totals AS
  SELECT client_id, sum(amount) AS total, count(*) AS cnt FROM ops.operations WHERE status = 1 GROUP BY client_id;
CREATE UNIQUE INDEX ON ops.totals (client_id);
CREATE TABLE ops.refresh_log (at timestamptz DEFAULT clock_timestamp(), flipped int);
CREATE FUNCTION ops.on_status_update() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v int;
BEGIN
  SELECT count(*) INTO v FROM o JOIN n USING (id, op_date) WHERE o.status = 0 AND n.status = 1;
  IF v > 0 THEN
    REFRESH MATERIALIZED VIEW CONCURRENTLY ops.totals;
    INSERT INTO ops.refresh_log (flipped) VALUES (v);
  END IF;
  RETURN NULL;
END $$;
CREATE TRIGGER t_stmt AFTER UPDATE ON ops.operations
  REFERENCING OLD TABLE AS o NEW TABLE AS n FOR EACH STATEMENT EXECUTE FUNCTION ops.on_status_update();
UPDATE ops.operations SET status = 1 WHERE status = 0 AND id % 2 = 0;
\echo '-- MV must equal live aggregate (sees own transaction changes):'
SELECT (SELECT sum(total) FROM ops.totals) AS mv_sum,
       (SELECT sum(amount) FROM ops.operations WHERE status = 1) AS live_sum;
\echo '-- same inside explicit transaction'
BEGIN;
UPDATE ops.operations SET status = 1 WHERE status = 0 AND id % 2 = 1 AND id < 200;
SELECT (SELECT sum(total) FROM ops.totals) AS mv_sum,
       (SELECT sum(amount) FROM ops.operations WHERE status = 1) AS live_sum;
COMMIT;
\echo '-- no-op update must not refresh'
UPDATE ops.operations SET status = 1 WHERE false;
UPDATE ops.operations SET amount = amount WHERE id = 2;
SELECT count(*) AS refresh_count, sum(flipped) FROM ops.refresh_log;

