-- =============================================================================
-- 02_operations.sql  (common: primary + replica)
-- Requirement 1: partitioned table T1 (ops.operations) + monthly partition maintenance.
--
-- Decisions: D-06 (RANGE by op_date, monthly + DEFAULT), D-13 (jsonb contract),
--            D-15 (naming), D-18 (self-healing maintenance), D-20 (search_path).
-- =============================================================================

CREATE TABLE IF NOT EXISTS ops.operations (
    -- BY DEFAULT (not ALWAYS): the subscriber must accept ids coming from the publisher.
    id              bigint        GENERATED BY DEFAULT AS IDENTITY,
    op_date         timestamptz   NOT NULL DEFAULT now(),
    amount          numeric(14,2) NOT NULL,
    status          smallint      NOT NULL DEFAULT 0,
    operation_guid  uuid          NOT NULL DEFAULT gen_random_uuid(),
    message         jsonb         NOT NULL,

    -- A PK / UNIQUE on a partitioned table must contain the partition key.
    -- The PK is also the replica identity for logical replication.
    CONSTRAINT operations_pk PRIMARY KEY (id, op_date),
    -- Target of the composite FK to the GUID registry (primary only, see 03_guid_registry.sql).
    CONSTRAINT operations_guid_date_uq UNIQUE (operation_guid, op_date),

    CONSTRAINT operations_amount_positive_ck CHECK (amount > 0),
    CONSTRAINT operations_status_ck          CHECK (status IN (0, 1)),

    -- jsonb message contract (D-13). CASE guards are used instead of AND because
    -- SQL does not guarantee evaluation order of AND operands.
    CONSTRAINT operations_message_object_ck
        CHECK (jsonb_typeof(message) = 'object'),
    CONSTRAINT operations_message_account_ck
        CHECK (CASE WHEN jsonb_typeof(message -> 'account_number') = 'string'
                    THEN (message ->> 'account_number') ~ '^UA[0-9]{27}$'
                    ELSE false END),
    CONSTRAINT operations_message_client_ck
        CHECK (CASE WHEN jsonb_typeof(message -> 'client_id') = 'number'
                    THEN (message ->> 'client_id') ~ '^[1-9][0-9]{0,17}$'
                    ELSE false END),
    CONSTRAINT operations_message_type_ck
        CHECK ((message ->> 'operation_type') IN ('online', 'offline'))
) PARTITION BY RANGE (op_date);

-- The confirm job (requirement 5) only ever looks at pending rows: keep that index tiny.
CREATE INDEX IF NOT EXISTS operations_pending_id_ix
    ON ops.operations (id) WHERE status = 0;

-- Per-client / per-type lookups (the same grouping as the materialized view).
-- The cast is safe: operations_message_client_ck is checked before index insertion.
CREATE INDEX IF NOT EXISTS operations_client_type_ix
    ON ops.operations (((message ->> 'client_id')::bigint), (message ->> 'operation_type'));

COMMENT ON TABLE  ops.operations                IS 'T1 from the task: operations, partitioned by month on op_date.';
COMMENT ON COLUMN ops.operations.op_date        IS 'Task: "дата" (date). Operation timestamp, partition key.';
COMMENT ON COLUMN ops.operations.id             IS 'Task: "айді" (id). Its parity drives the confirm job (requirement 5).';
COMMENT ON COLUMN ops.operations.amount         IS 'Task: "сума" (amount).';
COMMENT ON COLUMN ops.operations.status         IS 'Task: "стан" (status). 0 = pending, 1 = confirmed.';
COMMENT ON COLUMN ops.operations.operation_guid IS 'Task: "гуід операції" (operation guid). Globally unique, see ops.operation_guid_registry.';
COMMENT ON COLUMN ops.operations.message        IS 'Task: "повідомлення" (message, jsonb): {account_number, client_id, operation_type: online|offline}.';


-- -----------------------------------------------------------------------------
-- ops.create_month_partition(month) -> true if a partition was created
--
-- Normal path: CREATE TABLE ... PARTITION OF.
-- Self-healing path (D-18): if DEFAULT already holds rows of that month, a plain
-- CREATE ... PARTITION OF fails ("updated partition constraint for default partition
-- would be violated"). Then, in the same transaction:
--   1. DETACH the DEFAULT partition,
--   2. create the month table standalone and move the rows into it,
--   3. ATTACH the month table and re-ATTACH DEFAULT.
-- While the rows are moved, neither table is attached to ops.operations, so the
-- DELETE/INSERT are NOT published by logical replication (the publication is on the
-- partition root). A naive DELETE-from-DEFAULT + INSERT would publish the DELETE but
-- not the INSERT and silently desync the subscriber.
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION ops.create_month_partition(p_month date)
RETURNS boolean
LANGUAGE plpgsql
SET search_path = ops, pg_catalog
AS $$
DECLARE
    v_month date        := date_trunc('month', p_month)::date;
    v_lo    timestamptz := v_month::timestamp AT TIME ZONE 'UTC';
    v_hi    timestamptz := (v_month + interval '1 month')::timestamp AT TIME ZONE 'UTC';
    v_name  text        := format('operations_y%sm%s', to_char(v_month, 'YYYY'), to_char(v_month, 'MM'));
    v_cols  text;
    v_moved bigint;
BEGIN
    -- Same lock as ensure_monthly_partitions() (advisory xact locks are re-entrant),
    -- so direct calls of this function are serialised too.
    PERFORM pg_advisory_xact_lock(hashtext('ops.ensure_monthly_partitions'));

    IF to_regclass(format('ops.%I', v_name)) IS NOT NULL THEN
        RETURN false;
    END IF;

    IF to_regclass('ops.operations_default') IS NOT NULL
       AND EXISTS (SELECT 1 FROM ops.operations_default WHERE op_date >= v_lo AND op_date < v_hi)
    THEN
        ALTER TABLE ops.operations DETACH PARTITION ops.operations_default;

        EXECUTE format('CREATE TABLE ops.%I (LIKE ops.operations INCLUDING DEFAULTS INCLUDING CONSTRAINTS)', v_name);

        -- Explicit column list: robust against differing physical column order
        -- (e.g. after future ALTER TABLE ... DROP/ADD COLUMN on the parent).
        SELECT string_agg(quote_ident(attname), ', ' ORDER BY attnum) INTO v_cols
        FROM pg_attribute
        WHERE attrelid = 'ops.operations'::regclass AND attnum > 0 AND NOT attisdropped;

        EXECUTE format('INSERT INTO ops.%I (%s) SELECT %s FROM ops.operations_default WHERE op_date >= $1 AND op_date < $2',
                       v_name, v_cols, v_cols)
            USING v_lo, v_hi;
        DELETE FROM ops.operations_default WHERE op_date >= v_lo AND op_date < v_hi;
        GET DIAGNOSTICS v_moved = ROW_COUNT;

        EXECUTE format('ALTER TABLE ops.operations ATTACH PARTITION ops.%I FOR VALUES FROM (%L) TO (%L)', v_name, v_lo, v_hi);
        ALTER TABLE ops.operations ATTACH PARTITION ops.operations_default DEFAULT;

        RAISE NOTICE 'ops.create_month_partition: created % and moved % row(s) out of DEFAULT', v_name, v_moved;
    ELSE
        EXECUTE format('CREATE TABLE ops.%I PARTITION OF ops.operations FOR VALUES FROM (%L) TO (%L)', v_name, v_lo, v_hi);
    END IF;

    EXECUTE format('COMMENT ON TABLE ops.%I IS %L', v_name,
                   format('Monthly partition of ops.operations: [%s, %s)', v_lo, v_hi));
    RETURN true;
END;
$$;


-- -----------------------------------------------------------------------------
-- ops.ensure_monthly_partitions(from, months_ahead) -> number of partitions created
--
-- Ensures: DEFAULT partition; one partition per month from `p_from` up to
-- current month + `p_months_ahead`; plus a partition for every month that has
-- rows sitting in DEFAULT (e.g. replicated rows older than the subscriber's
-- initial range). Idempotent; serialised by an advisory lock.
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION ops.ensure_monthly_partitions(
    p_from         date DEFAULT (now() AT TIME ZONE 'UTC')::date,
    p_months_ahead int  DEFAULT 2
)
RETURNS int
LANGUAGE plpgsql
SET search_path = ops, pg_catalog
AS $$
DECLARE
    v_months  date[];
    v_month   date;
    v_created int := 0;
BEGIN
    IF p_months_ahead < 0 THEN
        RAISE EXCEPTION 'p_months_ahead must be >= 0, got %', p_months_ahead;
    END IF;

    PERFORM pg_advisory_xact_lock(hashtext('ops.ensure_monthly_partitions'));

    IF to_regclass('ops.operations_default') IS NULL THEN
        CREATE TABLE ops.operations_default PARTITION OF ops.operations DEFAULT;
        COMMENT ON TABLE ops.operations_default IS
            'Safety net. Must stay empty: ops.ensure_monthly_partitions moves rows out of it.';
    END IF;

    -- Materialise the month list first: a FOR-over-query loop would keep a cursor open
    -- on operations_default, and create_month_partition() may need to DETACH it
    -- ("cannot ALTER TABLE ... because it is being used by active queries").
    -- All month arithmetic is done on timestamp-without-time-zone values in UTC, so the
    -- result doesn't depend on the session TimeZone (partition bounds are UTC too).
    SELECT array_agg(m ORDER BY m) INTO v_months
    FROM (
        SELECT g::date AS m
        FROM generate_series(date_trunc('month', p_from::timestamp),
                             date_trunc('month', now() AT TIME ZONE 'UTC') + make_interval(months => p_months_ahead),
                             interval '1 month') AS g
        UNION
        SELECT DISTINCT date_trunc('month', op_date AT TIME ZONE 'UTC')::date
        FROM ops.operations_default
    ) months;

    FOREACH v_month IN ARRAY coalesce(v_months, '{}') LOOP
        IF ops.create_month_partition(v_month) THEN
            v_created := v_created + 1;
        END IF;
    END LOOP;

    RETURN v_created;
END;
$$;

COMMENT ON FUNCTION ops.create_month_partition(date) IS
    'Creates the monthly partition for the given month; moves matching rows out of DEFAULT if needed (D-18).';
COMMENT ON FUNCTION ops.ensure_monthly_partitions(date, int) IS
    'Idempotent partition maintenance: DEFAULT + months [p_from .. now + p_months_ahead] + months found in DEFAULT.';

-- Initial layout: covers the generator range (4 months back, D-11/Q3.2) and 2 months ahead.
-- Runs on both instances, so the subscriber has the partitions BEFORE it subscribes (R-03).
SELECT ops.ensure_monthly_partitions((now() - interval '4 months')::date, 2) AS partitions_created;

-- Daily maintenance on both instances: keeps 2 months ahead, heals DEFAULT.
-- cron.schedule() with a job name is an upsert, so re-running this script is safe.
SELECT cron.schedule('partition-maintenance', '15 0 * * *',
                     'SELECT ops.ensure_monthly_partitions()') AS partition_maintenance_job_id;
